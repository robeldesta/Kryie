"""Text sources for tokenizer training and data preparation.

A source spec is a string:

    hf:<dataset>[:<config>]:<split>:<text_field>   stream a Hugging Face dataset
    dir:<path>[:<glob>]                            read local files (default glob **/*.py)
    file:<path>                                    one document per line of a text file

A mixture is a list of "weight@spec" entries; documents are drawn from each
source in proportion to its weight.
"""

from __future__ import annotations

import glob
import hashlib
import os
import random
from typing import Iterator

# Defaults used when no --source is given. Code first, then a slice of
# Amharic and Afaan Oromo so the tokenizer learns Ge'ez script and Oromo words.
DEFAULT_CODE = ["1.0@hf:codeparrot/codeparrot-clean:train:content"]
DEFAULT_TOKENIZER_MIX = [
    "0.8@hf:codeparrot/codeparrot-clean:train:content",
    "0.1@hf:wikimedia/wikipedia:20231101.am:train:text",
    "0.1@hf:wikimedia/wikipedia:20231101.om:train:text",
]


def parse_count(s: str) -> int:
    """'100M' -> 100_000_000. Accepts K, M, B suffixes and underscores."""
    s = s.replace("_", "").upper()
    mult = {"K": 10**3, "M": 10**6, "B": 10**9}.get(s[-1], 1)
    return int(float(s[:-1] if s[-1] in "KMB" else s) * mult)


def iter_source(spec: str, seed: int = 0) -> Iterator[str]:
    kind, _, rest = spec.partition(":")
    if kind == "hf":
        parts = rest.split(":")
        if len(parts) == 3:
            name, split, field = parts
            config = None
        elif len(parts) == 4:
            name, config, split, field = parts
        else:
            raise ValueError(f"bad hf spec: {spec}")
        from datasets import load_dataset

        ds = load_dataset(name, config, split=split, streaming=True)
        ds = ds.shuffle(seed=seed, buffer_size=10_000)
        for row in ds:
            text = row.get(field)
            if text:
                yield text
    elif kind == "dir":
        path, _, pattern = rest.partition(":")
        files = sorted(glob.glob(os.path.join(path, pattern or "**/*.py"), recursive=True))
        random.Random(seed).shuffle(files)
        for f in files:
            try:
                with open(f, encoding="utf-8") as fh:
                    yield fh.read()
            except (UnicodeDecodeError, OSError):
                continue
    elif kind == "file":
        with open(rest, encoding="utf-8") as fh:
            for line in fh:
                line = line.strip()
                if line:
                    yield line
    else:
        raise ValueError(f"unknown source kind in {spec!r}")


def parse_mix(entries: list[str]) -> list[tuple[float, str]]:
    out = []
    for e in entries:
        w, sep, spec = e.partition("@")
        out.append((float(w), spec) if sep else (1.0, e))
    return out


def iter_mix(entries: list[str], seed: int = 0) -> Iterator[str]:
    """Interleave documents from several sources by weight until all run dry."""
    mix = parse_mix(entries)
    iters = [iter_source(spec, seed + i) for i, (_, spec) in enumerate(mix)]
    weights = [w for w, _ in mix]
    rng = random.Random(seed)
    while iters:
        i = rng.choices(range(len(iters)), weights=weights)[0]
        try:
            yield next(iters[i])
        except StopIteration:
            del iters[i], weights[i]


def keep_code(text: str, max_chars: int = 100_000) -> bool:
    """Cheap quality filter in the spirit of the Codex / StarCoder heuristics."""
    if len(text) < 32 or len(text) > max_chars:
        return False
    lines = text.splitlines()
    if not lines:
        return False
    if max(len(l) for l in lines) > 1000:
        return False
    if sum(len(l) for l in lines) / len(lines) > 100:
        return False
    alnum = sum(c.isalnum() for c in text) / len(text)
    if alnum < 0.25:
        return False
    head = text[:500].lower()
    if "auto-generated" in head or "autogenerated" in head or "do not edit" in head:
        return False
    return True


class ExactDedup:
    """Drop documents whose whitespace-normalised content was already seen."""

    def __init__(self):
        self.seen: set[bytes] = set()

    def __call__(self, text: str) -> bool:
        h = hashlib.blake2b(" ".join(text.split()).encode(), digest_size=12).digest()
        if h in self.seen:
            return False
        self.seen.add(h)
        return True
